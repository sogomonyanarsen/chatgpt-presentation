export const glyph = (name: string, className = 'glyph'): string => {
  const rows = GLYPHS[name];
  if (!rows) throw new Error(`Unknown glyph "${name}"`);
  const rects = rows
    .flatMap((row, y) =>
      Array.from({ length: row.length }, (_, x) => row.charAt(x)).map((cell, x) =>
        cell === '#' ? `<rect x="${x}" y="${y}" width="1" height="1"/>` : '',
      ),
    )
    .join('');
  return `<svg class="${className}" viewBox="0 0 9 9" aria-hidden="true" focusable="false" shape-rendering="crispEdges">${rects}</svg>`;
};
